/**
 * Deep-sky photographs from Stellarium's own catalogue
 * (`nebulae/default/textures.json`) — 38 of its 674 entries, kept lean
 * against the full ~130MB set, with their credits carried over.
 *
 * Each entry carries the thing that actually matters: the **four corners of
 * the image, as real sky coordinates**. That is Stellarium's own data model
 * — a `worldCoords` quad and a `textureCoords` quad, and the image is the
 * texture stretched across those four directions. It is emphatically not a
 * centre plus a size, and it is not anything to do with the screen: an
 * image is a patch *of the sky*, and the camera only ever decides whether
 * you are looking at it.
 *
 * The corners here are that same quad, converted once from the catalogue's
 * J2000 RA/Dec into the ecliptic longitude/latitude this app works in,
 * because that is what {@link place} — the one function every star in the
 * sky already goes through — takes. Converting at build time rather than
 * per frame is the only liberty taken; the geometry is Stellarium's.
 *
 * // are derived from those same corners (the centroid
 * direction, and the angle from it to the furthest corner) and exist only
 * for the cheap "is this anywhere near the view?" test. Nothing is ever
 * *drawn* from them.
 */

export type Nebula = {
  id: string;
  /** File under . */
  file: string;
  ne: string;
  en: string;
  /** Messier/NGC/Sharpless designation. */
  catalog: string;
  /** Photographer or observatory, from Stellarium's own catalogue. */
  credit: string;
  /**
   * The image's four corners as [ecliptic longitude, latitude] at J2000,
   * degrees — Stellarium's , converted from RA/Dec. In the
   * catalogue's own order, which pairs with {@link uv} corner for corner.
   */
  corners: [number, number][];
  /** Stellarium's `textureCoords`: which image corner goes on which sky corner. */
  uv: [number, number][];
  /** Centroid direction of the four corners — for the view test only. */
  lon: number;
  /** Centroid latitude — for the view test only. */
  lat: number;
  /** True angular width along the quad's own edges, degrees. */
  widthDeg: number;
  /** True angular height along the quad's own edges, degrees. */
  heightDeg: number;
  /** Centroid to furthest corner, degrees — the quad's bounding radius. */
  radiusDeg: number;
  /** Stellarium's own degrees-per-pixel figure for this image. */
  minResolution: number;
  /** Stellarium's own depth cutoff for this image. */
  maxBrightness: number;
};

